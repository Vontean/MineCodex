import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const source = await readFile(new URL("assets/brand/minecodex-icon.svg", root), "utf8");
const notice = "<!-- Generated by scripts/build-brand-icons.mjs from assets/brand/minecodex-icon.svg. -->\n";
const palette = { light: "#0d0d0d", dark: "#fafafa" };

// 原生选中图标填充外圈，镐子保留为透明孔；颜色由导航 currentColor 决定。
const outer = source.match(/<path id="codex-outline"[^>]* d="([^"]+)"/)[1].match(/^.*?Z/)[0];
const pickaxe = source.match(/<g id="pickaxe"[\s\S]*?<\/g>/)[0].replace('fill="currentColor"', 'fill="black"');
await writeFile(new URL("assets/brand/minecodex-icon-selected.svg", root), notice +
  `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24"><defs><mask id="pickaxe-cutout" maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24" style="mask-type:luminance"><rect width="24" height="24" fill="white"/>${pickaxe}</mask></defs><path fill="currentColor" mask="url(#pickaxe-cutout)" d="${outer}"/></svg>\n`);

// 外链 SVG 无法继承页面文字颜色，favicon 在资源内部响应系统主题。
for (const [theme, color] of Object.entries(palette)) {
  await writeFile(new URL(`assets/brand/minecodex-icon-${theme}.svg`, root),
    notice + source.replace('fill="none" role=', `color="${color}" fill="none" role=`));
}
const favicon = source.replace("  <title", `  <style>\n    :root { color: ${palette.light}; }\n    @media (prefers-color-scheme: dark) { :root { color: ${palette.dark}; } }\n  </style>\n  <title`);
await writeFile(new URL("apps/dashboard/favicon.svg", root), notice + favicon);

// README 头图分浅色、深色两份，由 <picture> 按 GitHub 主题选择；标签胶囊内的品牌标识由同一源文件生成。
const geometry = source.slice(source.indexOf('  <path id="codex-outline"'), source.lastIndexOf("</svg>"));
for (const [file, color] of [["hero.svg", palette.light], ["hero-dark.svg", palette.dark]]) {
  const heroUrl = new URL(`assets/readme/${file}`, root);
  const hero = await readFile(heroUrl, "utf8");
  const pattern = /<!-- MineCodex brand start -->[\s\S]*?<!-- MineCodex brand end -->/;
  if (!pattern.test(hero)) throw new Error(`assets/readme/${file} is missing the MineCodex brand markers`);
  const mark = `<!-- MineCodex brand start -->\n    <g transform="translate(16 8)" color="${color}" fill="none">\n${geometry}    </g>\n    <!-- MineCodex brand end -->`;
  await writeFile(heroUrl, hero.replace(pattern, mark));
}
console.log(`Generated MineCodex theme icons, dashboard favicon and README mark from ${fileURLToPath(new URL("assets/brand/minecodex-icon.svg", root))}`);

const serviceIcon = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <rect x="64" y="64" width="896" height="896" rx="200" fill="#fafafa"/>
  <g transform="translate(128 128) scale(32)" color="#0d0d0d" fill="none">
${geometry}  </g>
</svg>
`;
await writeFile(new URL("assets/brand/minecodex-service-icon.svg", root), notice + serviceIcon);
